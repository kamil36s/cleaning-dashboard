function normalizeAuthorName(value) {
  return String(value || '')
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[’']/g, '')
    .toLocaleLowerCase('pl')
    .replace(/\s+/g, ' ')
    .trim();
}

