const NOBEL_AUTHOR_SET = new Set(
  NOBEL_READING_BOOKS_RAW.map((book) => normalizeAuthorName(book.author)),
);

const NOBEL_AUTHOR_YEAR_MAP = new Map(
  NOBEL_READING_BOOKS_RAW.map((book, index) => [
    normalizeAuthorName(book.author),
    NOBEL_AUTHOR_YEARS[index] || null,
  ]),
);

export function isNobelAuthor(author) {
  return NOBEL_AUTHOR_SET.has(normalizeAuthorName(author));
}

export function getNobelAuthorYear(author) {
  return NOBEL_AUTHOR_YEAR_MAP.get(normalizeAuthorName(author)) || null;
}
